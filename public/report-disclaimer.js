// Shared report disclaimer for every Commons tool that produces a report.
// One wording, used on screen and in PDFs, so the tools can't drift apart.
//
// Load with <script src="/report-disclaimer.js"></script>, then:
//   CommonsDisclaimer.html(opts)            -> HTML string for the on-screen report
//   CommonsDisclaimer.pdfBlock(doc, x, y, w, opts) -> draws the full box in a jsPDF doc, returns new y
//   CommonsDisclaimer.pdfFooter(doc, opts)  -> one short line at the bottom of every PDF page
//
// opts = {
//   tool:    "Validation Protocol Generator",
//   version: "2026-10-29",              // tool version: the date its logic last changed
//   ai:      "none" | "partial" | "full", // how much of the report an AI wrote
//   date:    optional Date, defaults to now
// }
(function () {
  var CONTACT = "lmlamerereads@gmail.com";

  var AI_LINE = {
    none: "It is built from fixed rules applied to your answers. No AI wrote any part of it.",
    partial: "Parts of it were written by AI, and those parts are marked as AI-generated.",
    full: "It was written by AI from your answers.",
  };

  function fmtDate(d) {
    return (d || new Date()).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
  }

  function parts(opts) {
    opts = opts || {};
    var tool = opts.tool || "Commons tool";
    var version = opts.version || "unversioned";
    return {
      heading: "Working prototype",
      sentences: [
        "This report was generated by the Healthcare Governance Commons " + tool + " (version " + version + ") on " + fmtDate(opts.date) + ".",
        AI_LINE[opts.ai] || AI_LINE.partial,
        "Neither the tool nor this report has been independently reviewed.",
        "It is not clinical, legal, or financial advice, and it does not replace your organization's own validation, review, and sign-off.",
        "Send problems to " + CONTACT + ".",
      ],
      footer: "Working prototype · not independently reviewed · not clinical, legal or financial advice · " +
        tool + " v" + version + " · problems: " + CONTACT,
    };
  }

  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; });
  }

  function html(opts) {
    var p = parts(opts);
    var body = p.sentences.map(esc).join(" ").replace(esc(CONTACT), '<a href="mailto:' + CONTACT + '" style="color:inherit">' + CONTACT + "</a>");
    return '<div class="commons-disclaimer" role="note" style="margin:20px 0;padding:14px 16px;border:1px solid rgba(167,139,250,.55);' +
      'border-left:4px solid #a78bfa;border-radius:6px;background:rgba(167,139,250,.08);font:14px/1.55 system-ui,sans-serif;text-align:left">' +
      '<strong style="display:block;margin-bottom:4px">' + esc(p.heading) + "</strong>" + body + "</div>";
  }

  // jsPDF: bordered box with the full wording. Returns the y just below the box.
  function pdfBlock(doc, x, y, w, opts) {
    var p = parts(opts);
    var pad = 10;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    var lines = doc.splitTextToSize(p.sentences.join(" "), w - pad * 2);
    var h = pad + 12 + lines.length * 10 + pad - 2;
    doc.setFillColor(243, 240, 251);
    doc.rect(x, y, w, h, "F");
    doc.setDrawColor(124, 98, 196);
    doc.setLineWidth(0.75);
    doc.rect(x, y, w, h, "S");
    doc.setFillColor(124, 98, 196);
    doc.rect(x, y, 3, h, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(60, 40, 120);
    doc.text(p.heading.toUpperCase(), x + pad + 2, y + pad + 6);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(42, 42, 42);
    doc.text(lines, x + pad + 2, y + pad + 18);
    return y + h;
  }

  // jsPDF: short line on every page, just above where page numbers usually go.
  function pdfFooter(doc, opts) {
    var p = parts(opts);
    var w = doc.internal.pageSize.getWidth();
    var h = doc.internal.pageSize.getHeight();
    var n = doc.getNumberOfPages();
    for (var i = 1; i <= n; i++) {
      doc.setPage(i);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(6.5);
      doc.setTextColor(110, 100, 140);
      doc.text(doc.splitTextToSize(p.footer, w - 108), w / 2, h - 34, { align: "center" });
    }
  }

  window.CommonsDisclaimer = { CONTACT: CONTACT, parts: parts, html: html, pdfBlock: pdfBlock, pdfFooter: pdfFooter };
})();
