// Builds the offline Local Validation Kit: one self-contained HTML file with the
// engine, rule packs and sample inlined, and a stricter security policy
// (default-src 'none': it can't load or send anything). Writes its SHA-256 next to it
// and into offline-hash.js, which the online page shows so a security team can check
// a downloaded copy. Deterministic: same source, same file, same hash.
// Usage: node scripts/build-kit-offline.mjs          (build)
//        node scripts/build-kit-offline.mjs --verify (fail if the committed copy is stale)
import { readFileSync, writeFileSync } from "fs";
import { createHash } from "crypto";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public/local-validation");
const read = (f) => readFileSync(join(dir, f), "utf8");
const SITE = "https://healthcare-governance-commons.vercel.app";

let html = read("index.html");
const inline = (file) => `<script>\n// ${file} (inlined for the offline copy)\n${read(file).replace(/<\/script/gi, "<\\/script")}\n</script>`;
// The "See how it works" images live on the website; the offline copy can't load them.
html = html.replace(/\n  <!--howto-->[\s\S]*?<!--\/howto-->/, "");
html = html.replace('<script src="offline-hash.js"></script>', "<script>window.LVK_OFFLINE = true;</script>");
for (const f of ["engine.js", "sepsis-ase.js", "sample-sepsis.js"]) {
  const tag = `<script src="${f}"></script>`;
  if (!html.includes(tag)) throw new Error(`index.html no longer loads ${f}`);
  html = html.replace(tag, () => inline(f));
}
html = html.replace(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/,
  `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; connect-src 'none'; form-action 'none'; base-uri 'none'">`);
html = html.replace(/href="\//g, `href="${SITE}/`);
html = html.replace("<title>Local Validation Kit</title>", "<title>Local Validation Kit (offline copy)</title>");

const hash = createHash("sha256").update(html).digest("hex");
const out = join(dir, "local-validation-kit-offline.html");
if (process.argv.includes("--verify")) {
  let have = "";
  try { have = readFileSync(out, "utf8"); } catch {}
  const hashJs = (() => { try { return read("offline-hash.js"); } catch { return ""; } })();
  if (have !== html || !hashJs.includes(hash)) { console.error("offline kit is stale: run node scripts/build-kit-offline.mjs"); process.exit(1); }
  console.log("offline kit up to date", hash);
} else {
  writeFileSync(out, html);
  writeFileSync(out + ".sha256", `${hash}  local-validation-kit-offline.html\n`);
  writeFileSync(join(dir, "offline-hash.js"), `// Generated by scripts/build-kit-offline.mjs. SHA-256 of local-validation-kit-offline.html.\nwindow.LVK_OFFLINE_HASH = "${hash}";\n`);
  console.log(hash, (html.length / 1024).toFixed(0) + " KB");
}
