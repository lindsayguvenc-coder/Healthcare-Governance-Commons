# Makes public/local-validation/sample-sepsis.csv: made-up encounters for trying the
# Local Validation Kit. No real patients. Fixed seed, so the file is the same every run.
# Usage: python3 scripts/make-sample-sepsis.py
import csv, random
random.seed(20261113)
rows = []
groups = dict(age_group=["18-44", "45-64", "65+"], sex=["F", "M"],
              race_ethnicity=["Black", "Hispanic", "White", "Asian", "Other"],
              language=["English", "Spanish", "Other"], payer=["Medicaid", "Medicare", "Commercial", "Uninsured"])
for i in range(1, 801):
    g = {k: random.choice(v) for k, v in groups.items()}
    r = random.random()
    row = dict(encounter_id=f"E{i:04d}", **g)
    # about 14% get a culture with a full antibiotic course; about 30% a culture and a short course
    if r < 0.14:
        row.update(blood_culture=1, qad_count=random.choice([4, 5, 6, 7, 9]), short_course_ok=0)
    elif r < 0.44:
        q = random.choice([0, 1, 2, 3])
        row.update(blood_culture=1, qad_count=q, short_course_ok=1 if random.random() < 0.08 else 0)
    else:
        row.update(blood_culture=0, qad_count=0, short_course_ok=0)
    infected = row["blood_culture"] == 1 and (row["qad_count"] >= 4 or (row["qad_count"] >= 1 and row["short_course_ok"] == 1))
    sick = infected and random.random() < 0.8
    row.update(
        vasopressor_start=1 if sick and random.random() < 0.35 else 0,
        mech_vent_start=1 if sick and random.random() < 0.2 else 0,
        lactate_max=round(random.uniform(2.1, 6.0) if sick and random.random() < 0.6 else random.uniform(0.6, 1.7), 1),
        creatinine_ratio=round(random.uniform(2.0, 3.5) if sick and random.random() < 0.3 else random.uniform(0.8, 1.5), 2),
        esrd=1 if random.random() < 0.03 else 0,
        bilirubin_max=round(random.uniform(2.1, 5) if sick and random.random() < 0.15 else random.uniform(0.3, 1.4), 1),
        bilirubin_ratio=round(random.uniform(2.1, 4) if sick and random.random() < 0.15 else random.uniform(0.8, 1.5), 2),
        platelet_min=random.randint(40, 95) if sick and random.random() < 0.15 else random.randint(140, 380),
        platelet_baseline=random.randint(160, 380),
    )
    # the model: higher scores for the truly sick, some misses and false alarms
    base = 0.62 if sick else (0.32 if infected else 0.12)
    row["model_score"] = round(min(0.99, max(0.01, random.gauss(base, 0.16))), 2)
    rows.append(row)
# borderline and missing cases, so the workqueue has something to do
for row in random.sample(rows, 40):
    k = random.choice(["lac", "blank_qad", "blank_short", "esrd_blank", "cr_near"])
    if k == "lac": row["blood_culture"] = 1; row["qad_count"] = 5; row["lactate_max"] = random.choice([1.9, 2.0, 2.1])
    if k == "blank_qad": row["blood_culture"] = 1; row["qad_count"] = ""
    if k == "blank_short": row["blood_culture"] = 1; row["qad_count"] = 2; row["short_course_ok"] = ""
    if k == "esrd_blank": row["blood_culture"] = 1; row["qad_count"] = 6; row["creatinine_ratio"] = 2.4; row["esrd"] = ""
    if k == "cr_near": row["blood_culture"] = 1; row["qad_count"] = 4; row["creatinine_ratio"] = 1.9; row["lactate_max"] = 1.2; row["vasopressor_start"] = 0; row["mech_vent_start"] = 0
cols = ["encounter_id", "model_score", "blood_culture", "qad_count", "short_course_ok", "vasopressor_start", "mech_vent_start",
        "lactate_max", "creatinine_ratio", "esrd", "bilirubin_max", "bilirubin_ratio", "platelet_min", "platelet_baseline",
        "age_group", "sex", "race_ethnicity", "language", "payer"]
with open("public/local-validation/sample-sepsis.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(rows)
print(len(rows))
